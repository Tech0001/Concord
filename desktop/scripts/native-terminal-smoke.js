const invoke = (cmd, args) => window.__TAURI_INTERNALS__.invoke(cmd, args);
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const assert = (ok, message) => { if (!ok) throw Error(message); };
const until = async (check, label) => {
  for (let i = 0; i < 200; i++) { if (await check()) return; await sleep(100); }
  throw Error(`Timed out: ${label}`);
};
const click = (text, scope = document) => {
  const button = [...scope.querySelectorAll('button')].find(e => e.textContent.trim() === text);
  assert(button && !button.disabled, `Available button: ${text}`); button.click();
};
await invoke('start_library');
await invoke('setup_save', { patch: { completed: true } });
location.hash = '#/library';
await until(() => document.querySelector('.activity-item'), 'status entry');
document.querySelector('.activity-item').click();
await until(() => document.querySelector('.archive-tabs'), 'status workspace');
click('Terminal', document.querySelector('.archive-tabs'));
await until(() => document.querySelector('.terminal-line'), 'activity logs');
assert(!document.querySelector('.level-debug'), 'Activity hides diagnostic entries');
click('Debug', document.querySelector('.terminal-controls'));
await until(() => document.querySelector('.level-debug'), 'debug mode');
assert(document.querySelector('.terminal-output').textContent.includes('SQLite WAL'), 'Startup detail retained before opening terminal');
const id = await invoke('pipeline_save_source', { source: { id: null, name: 'Native terminal source', kind: 'folder', url: config.root + '/incoming', enabled: true, diarize: false, includeShorts: false, category: 'personal' }});
await invoke('pipeline_check', { id, full: false });
await until(async () => !(await invoke('pipeline_state')).checking, 'source scan');
await until(() => document.querySelector('.terminal-output').textContent.includes('Queued 2; skipped 0'), 'live scan diagnostic');
assert((await invoke('pipeline_state')).running === false, 'Transcription stays paused');
const diagnosticCount = document.querySelectorAll('.level-debug').length;
click('Activity', document.querySelector('.terminal-controls'));
await until(() => !document.querySelector('.level-debug'), 'Switch returns to readable activity');
assert(document.querySelector('.terminal-output').textContent.includes('2 new recordings queued'), 'Activity retained beside debug');
click('Debug', document.querySelector('.terminal-controls'));
await until(() => document.querySelectorAll('.level-debug').length === diagnosticCount, 'Mode switch retains earlier diagnostics');
click('Pause', document.querySelector('.terminal-controls'));
await until(() => document.querySelector('.terminal-controls').textContent.includes('Resume'), 'pause rendered');
const before = document.querySelectorAll('.terminal-line').length;
await invoke('pipeline_check', { id, full: false });
await until(async () => !(await invoke('pipeline_state')).checking, 'repeat source scan');
await until(() => document.querySelector('.terminal-controls').textContent.includes('Resume ('), 'pause buffer');
assert(document.querySelectorAll('.terminal-line').length === before, 'Paused screen is stable');
const resume = [...document.querySelectorAll('.terminal-controls button')].find(b => b.textContent.startsWith('Resume'));
resume.click();
await until(() => document.querySelector('.terminal-output').textContent.includes('Queued 0; skipped 2'), 'resume restores diagnostics');
const input = document.querySelector('[aria-label="Filter log output"]');
Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'source scan');
input.dispatchEvent(new Event('input', { bubbles: true }));
await until(() => [...document.querySelectorAll('.terminal-line')].every(e => e.textContent.toLowerCase().includes('source scan')), 'filter diagnostics');
assert(document.querySelectorAll('.terminal-line').length >= 2, 'filtered diagnostics present');
click('Clear', document.querySelector('.terminal-controls'));
await until(() => !document.querySelector('.terminal-line'), 'cleared view');
await sleep(1200);
assert(!document.querySelector('.terminal-line'), 'Clear does not immediately replay old entries');
return { checks: ['activity/debug separation', 'startup diagnostics retained', 'live folder scan counts', 'paused queue unchanged', 'mode switch retention', 'pause/resume', 'filter', 'clear'], logs: (await invoke('runtime_logs', { after: 0 })).length };
